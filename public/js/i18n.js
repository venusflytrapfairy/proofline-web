let current = "en";

export const getLang = () => current;

export function setLang(lang) {
  current = lang === "ar" ? "ar" : "en";
  if (typeof document !== "undefined") {
    document.documentElement.lang = current;
    document.documentElement.dir = current === "ar" ? "rtl" : "ltr";
  }
}

// Pick the right language from a {en, ar} pair; plain values pass through.
export function L(v, lang = current) {
  if (v && typeof v === "object" && !Array.isArray(v) && ("en" in v || "ar" in v)) return v[lang] ?? v.en;
  return v;
}

export function t(key, vars = {}, lang = current) {
  const e = STR[key];
  const s = e ? (lang === "ar" ? e[1] ?? e[0] : e[0]) : key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ""));
}

